package org.apache.cassandra.sidecar.handlers;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import com.google.inject.Inject;
import com.google.inject.Singleton;
import io.netty.handler.codec.http.HttpResponseStatus;
import io.vertx.core.Handler;
import io.vertx.ext.web.RoutingContext;
import org.apache.cassandra.sidecar.config.OpenApiConfiguration;
import org.apache.cassandra.sidecar.config.SidecarConfiguration;

/**
 * Handler that serves the OpenAPI specification
 * 
 * This handler serves the OpenAPI specification generated by the Gradle openApiGenerate task
 * which processes JAX-RS/MicroProfile annotations to create comprehensive API documentation.
 */
@Singleton
public class OpenApiHandler implements Handler<RoutingContext>
{
    private static final Logger logger = LoggerFactory.getLogger(OpenApiHandler.class);
    private final OpenApiConfiguration openApiConfig;
    

    @Inject
    public OpenApiHandler(SidecarConfiguration sidecarConfiguration)
    {
        this.openApiConfig = sidecarConfiguration.openApiConfiguration();
    }

    @Override
    public void handle(RoutingContext context)
    {
        try
        {
            // Determine format from request path or Accept header
            boolean isYaml = isYamlRequest(context);
            String openApiContent = loadGeneratedOpenApiSpec(isYaml);
            String contentType = isYaml ? "application/yaml" : "application/json";
            
            context.response()
                   .putHeader("Content-Type", contentType)
                   .end(openApiContent);
        }
        catch (Exception e)
        {
            logger.warn("Failed to load generated OpenAPI specification, falling back to basic config", e);
            context.response().setStatusCode(HttpResponseStatus.NOT_FOUND.code())
                   .putHeader("Content-Type", "application/json")
                   .end();
        }
    }

    /**
     * Determines if the request is for YAML format based on path or Accept header
     */
    private boolean isYamlRequest(RoutingContext context)
    {
        String path = context.request().path();
        if (path != null && path.endsWith(".yaml"))
        {
            return true;
        }
        
        String acceptHeader = context.request().getHeader("Accept");
        return acceptHeader != null && acceptHeader.contains("application/yaml");
    }
    
    /**
     * Loads the generated OpenAPI specification from resources or build output
     */
    private String loadGeneratedOpenApiSpec(boolean isYaml) throws IOException
    {
        // First try to load from classpath resources (for packaged deployments)
        String content = loadFromClasspathResource(isYaml);
        if (content != null)
        {
            return content;
        }

        // Fallback to file system paths (for development)
        return loadFromFileSystem(isYaml);
    }

    /**
     * Attempts to load the OpenAPI spec from classpath resources
     */
    private String loadFromClasspathResource(boolean isYaml) throws IOException
    {
        String fileName = isYaml ? "openapi.yaml" : "openapi.json";
        String resourcePath = "/openapi/" + fileName;
        
        InputStream inputStream = getClass().getResourceAsStream(resourcePath);
        if (inputStream == null)
        {
            return null;
        }
        
        logger.debug("Loading OpenAPI specification from classpath: {}", resourcePath);
        try 
        {
            byte[] bytes = inputStream.readAllBytes();
            String content = new String(bytes, StandardCharsets.UTF_8);
            logger.info("Loaded OpenAPI specification from classpath resource");
            return content;
        }
        finally
        {
            inputStream.close();
        }
    }

    /**
     * Attempts to load the OpenAPI spec from file system (development mode)
     */
    private String loadFromFileSystem(boolean isYaml) throws IOException
    {
        String fileName = isYaml ? "openapi.yaml" : "openapi.json";
        String[] possiblePaths = {
            "server/build/generated/openapi/" + fileName,    // From project root
            "build/generated/openapi/" + fileName,           // From server directory
            "../server/build/generated/openapi/" + fileName, // Alternative relative path
        };
        
        Path foundPath = null;
        for (String pathStr : possiblePaths)
        {
            Path path = Paths.get(pathStr);
            if (Files.exists(path))
            {
                foundPath = path;
                break;
            }
        }
        
        if (foundPath == null)
        {
            throw new IOException("Generated OpenAPI specification not found in classpath resources or file system. " +
                                "Please run './gradlew openApiGenerate' and ensure the generated file is included in the build.");
        }
        
        logger.debug("Loading OpenAPI specification from: {}", foundPath.toAbsolutePath());
        String content = Files.readString(foundPath, StandardCharsets.UTF_8);
        logger.info("Loaded OpenAPI specification from {}", foundPath.toAbsolutePath());
        
        return content;
    }
}
